namespace TigerCS.Tests.EmployeeReviews;

/// <summary>
/// A real relational database (SQLite in memory, the real EF-mapped schema, foreign keys enforced) behind the real Employee Review
/// repository and services, so unique indexes, scope joins and date ranges are proven as SQL rather than by a fake.
/// </summary>
public sealed class EmployeeReviewFixture : IDisposable
{
    /// <summary>SQL Server row versions cannot be generated by SQLite; the schema gives them a default. Nothing under test changes.</summary>
    private sealed class SqliteTigerCsDbContext(DbContextOptions<TigerCsDbContext> options) : TigerCsDbContext(options)
    {
        protected override void OnModelCreating(ModelBuilder builder)
        {
            base.OnModelCreating(builder);
            builder.Entity<Ticket>().Property(t => t.RowVersion).HasDefaultValueSql("X'0000000000000000'");
            builder.Entity<TicketAgentHandoff>().Property(h => h.RowVersion).HasDefaultValueSql("X'0000000000000000'");
            builder.Entity<CustomerContactDetail>().Property(c => c.RowVersion).HasDefaultValueSql("X'0000000000000000'");
            builder.Entity<CustomerPropertyAssociation>().Property(c => c.RowVersion).HasDefaultValueSql("X'0000000000000000'");
            builder.Entity<CustomerProfileOverride>().Property(c => c.RowVersion).HasDefaultValueSql("X'0000000000000000'");
            builder.Entity<TigerCS.Domain.Modules.QueueingIntegration.QueueingTicketLink>().Property(l => l.RowVersion).HasDefaultValueSql("X'0000000000000000'");
        }
    }

    public sealed class FixedTimeProvider(DateTime utcNow) : TimeProvider
    {
        public DateTime UtcNow { get; set; } = utcNow;

        public override DateTimeOffset GetUtcNow() => new(DateTime.SpecifyKind(UtcNow, DateTimeKind.Utc), TimeSpan.Zero);
    }

    private sealed class NoServiceIdentities : IServiceIdentityRegistry
    {
        public bool IsServiceIdentity(Guid employeeId) => false;

        public IReadOnlyCollection<Guid> ServiceIdentityIds => [];
    }

    private sealed class DbAuditWriter(TigerCsDbContext db) : IAuditEntryWriter
    {
        public async Task WriteAsync(Guid? actorEmployeeId, string action, string entityType, string? entityId, string? beforeValue, string? afterValue,
            Guid correlationId, CancellationToken cancellationToken = default) =>
            await db.AuditEntries.AddAsync(new TigerCS.Domain.Audit.AuditEntry(
                actorEmployeeId, action, entityType, entityId, beforeValue, afterValue, correlationId, DateTime.UtcNow), cancellationToken);
    }

    private readonly SqliteConnection _connection = new("DataSource=:memory:");

    /// <summary>Mid-day on 10 Sep 2026 UTC (16:00 UAE).</summary>
    public static readonly DateTime Now = new(2026, 9, 10, 12, 0, 0, DateTimeKind.Utc);

    public FixedTimeProvider Time { get; } = new(Now);

    public int CustomerServiceId { get; private set; }
    public int CollectionsId { get; private set; }

    public Guid Amal { get; } = Guid.NewGuid();        // CS Agent, Customer Service
    public Guid Bilal { get; } = Guid.NewGuid();       // CS Agent, Customer Service
    public Guid Hadi { get; } = Guid.NewGuid();        // Collections (not Customer Service)
    public Guid Supervisor { get; } = Guid.NewGuid();  // CS Supervisor, Customer Service
    public Guid Manager { get; } = Guid.NewGuid();     // CS Manager
    public Guid Admin { get; } = Guid.NewGuid();       // System Administrator
    public Guid Departed { get; } = Guid.NewGuid();    // CS Agent, deactivated

    public EmployeeReviewFixture()
    {
        _connection.Open();
        using var context = CreateContext();
        context.Database.EnsureCreated();
        Seed(context);
    }

    public TigerCsDbContext CreateContext() => new SqliteTigerCsDbContext(
        new DbContextOptionsBuilder<TigerCsDbContext>()
            .UseSqlite(_connection)
            .ConfigureWarnings(w => w.Ignore(RelationalEventId.AmbientTransactionWarning))
            .Options);

    public EmployeeReviewRepository CreateRepository(TigerCsDbContext context) => new(context, new NoServiceIdentities());

    public EmployeeReviewTabletService CreateTabletService(TigerCsDbContext context) => new(CreateRepository(context), Time);

    public EmployeeReviewDeviceAdminService CreateAdminService(TigerCsDbContext context) =>
        new(CreateRepository(context), new DbAuditWriter(context), Time);

    public EmployeeReviewQueryAppService CreateQueryService(TigerCsDbContext context) =>
        new(CreateRepository(context), new UserDepartmentAssignmentRepository(context), Time);

    /// <summary>Registers a tablet through the real admin service and returns the device id with its one-time token.</summary>
    public async Task<(Guid DeviceId, string Token)> RegisterAsync(string name, Guid employeeId)
    {
        using var context = CreateContext();
        var result = await CreateAdminService(context).RegisterAsync(Admin, new(name, employeeId));
        Assert.True(result.IsSuccess, string.Join("; ", result.Errors ?? []));
        return (result.Value!.Device.Id, result.Value.Token);
    }

    /// <summary>Stores a review through the real tablet service at <paramref name="atUtc"/>.</summary>
    public async Task SubmitAsync(string token, int rating, string? comment, DateTime atUtc, Guid? submissionId = null)
    {
        var previous = Time.UtcNow;
        Time.UtcNow = atUtc;
        try
        {
            using var context = CreateContext();
            var result = await CreateTabletService(context).SubmitAsync(token, new(submissionId ?? Guid.NewGuid(), rating, comment));
            Assert.Equal(TigerCS.Application.Modules.EmployeeReviews.Dto.SubmitEmployeeReviewOutcome.Submitted, result.Outcome);
        }
        finally
        {
            Time.UtcNow = previous;
        }
    }

    private void Seed(TigerCsDbContext context)
    {
        var cs = new Department("Customer Service", "CS");
        var collections = new Department("Collections", "COL");
        context.Departments.AddRange(cs, collections);
        context.SaveChanges();
        CustomerServiceId = cs.DepartmentId;
        CollectionsId = collections.DepartmentId;

        AddEmployee(context, Amal, "Amal Agent", Roles.CsAgent, CustomerServiceId);
        AddEmployee(context, Bilal, "Bilal Agent", Roles.CsAgent, CustomerServiceId);
        AddEmployee(context, Hadi, "Hadi Head", Roles.DepartmentHead, CollectionsId);
        AddEmployee(context, Supervisor, "Sara Supervisor", Roles.CsSupervisor, CustomerServiceId);
        AddEmployee(context, Manager, "Mona Manager", Roles.CsManager, CustomerServiceId);
        AddEmployee(context, Admin, "Adam Admin", Roles.SystemAdministrator, null);
        AddEmployee(context, Departed, "Dina Departed", Roles.CsAgent, CustomerServiceId);
        context.Employees.Single(e => e.EmployeeId == Departed).Deactivate(Now.AddDays(-1));
        context.SaveChanges();
    }

    private static void AddEmployee(TigerCsDbContext context, Guid id, string name, string role, int? departmentId)
    {
        context.Users.Add(new ApplicationUser
        {
            Id = id,
            UserName = $"user-{id:N}",
            NormalizedUserName = $"USER-{id:N}",
            Email = $"user-{id:N}@example.test",
            SecurityStamp = Guid.NewGuid().ToString()
        });
        context.Employees.Add(new Employee(id, name, isGeynessStaff: false, Now.AddDays(-60)));

        var roleRow = context.Roles.FirstOrDefault(r => r.Name == role);
        if (roleRow is null)
        {
            roleRow = new ApplicationRole(role, role) { Id = Guid.NewGuid(), NormalizedName = role.ToUpperInvariant() };
            context.Roles.Add(roleRow);
        }

        context.SaveChanges();
        context.UserRoles.Add(new IdentityUserRole<Guid> { UserId = id, RoleId = roleRow.Id });
        if (departmentId is { } department)
        {
            context.UserDepartmentAssignments.Add(new UserDepartmentAssignment(id, department, true, Now.AddDays(-50), null));
        }

        context.SaveChanges();
    }

    public void Dispose() => _connection.Dispose();
}
